// Inlines lib/ui.html (and the QR scanner library it loads on demand) into
// lib/ui.generated.js so the UI ships inside the Bare bundle on Android
// (no filesystem assets needed).
import fs from 'node:fs'

const read = (rel) => fs.readFileSync(new URL(rel, import.meta.url), 'utf8')
const out = new URL('../lib/ui.generated.js', import.meta.url)
const code = '// Generated by scripts/embed-ui.js from ui.html. Do not edit.\n' +
  'export default ' + JSON.stringify(read('../lib/ui.html')) + '\n' +
  'export const jsQR = ' + JSON.stringify(read('../node_modules/jsqr/dist/jsQR.js')) + '\n'
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== code) fs.writeFileSync(out, code)
