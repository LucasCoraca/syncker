// Writes the Android app's icons (Icons.kt) from the SVG symbols in lib/ui.html,
// so the phone and the web UI draw the same icons. Run by build-android.sh.
import fs from 'fs'
import path from 'path'

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..')
const html = fs.readFileSync(path.join(root, 'lib/ui.html'), 'utf8')
const out = path.join(root, 'android/app/src/main/java/app/syncker/ui/Icons.kt')

const icons = []
for (const m of html.matchAll(/<symbol id="([^"]+)" viewBox="0 0 (\d+) (\d+)">([\s\S]*?)<\/symbol>/g)) {
  const [, id, w, h, body] = m
  const paths = [...body.matchAll(/<path(?: fill="([^"]+)")? d="([^"]+)"\/>/g)].map(([, fill, d]) => ({ fill, d }))
  if (!paths.length) throw new Error(`symbol ${id}: no paths`)
  icons.push({ id, w, h, paths })
}

const str = (s) => JSON.stringify(s).replace(/\$/g, '\\$')
const color = (c) => {
  if (!c) return 'null'
  const hex = c === '#fff' ? 'ffffff' : c.slice(1)
  if (!/^[0-9a-f]{6}$/i.test(hex)) throw new Error('unsupported fill ' + c)
  return `Color(0xFF${hex.toUpperCase()})`
}

const kt = `// Generated by scripts/icons-kt.js from lib/ui.html: don't edit by hand.
package app.syncker.ui

import androidx.compose.ui.graphics.Color

internal class IconPath(val fill: Color?, val d: String)
internal class IconData(val w: Float, val h: Float, val paths: List<IconPath>)

internal val ICON_DATA: Map<String, IconData> = mapOf(
${icons.map((i) => `    ${str(i.id)} to IconData(${i.w}f, ${i.h}f, listOf(${i.paths.map((p) => `IconPath(${color(p.fill)}, ${str(p.d)})`).join(', ')}))`).join(',\n')}
)
`
fs.mkdirSync(path.dirname(out), { recursive: true })
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== kt) fs.writeFileSync(out, kt)
console.log(`${icons.length} icons -> ${path.relative(root, out)}`)
